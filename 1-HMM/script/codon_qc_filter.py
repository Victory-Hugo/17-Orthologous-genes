def parse_fasta(path: str) -> "OrderedDict[str, str]":
    seqs: "OrderedDict[str, str]" = OrderedDict()
    name: str | None = None
    buf: List[str] = []
    with open(path) as fh:
        for line in fh:
            if line.startswith(">"):
                if name is not None:
                    seqs[name] = "".join(buf).replace(" ", "").replace("\t", "")
                name = line[1:].strip()
                buf = []
            else:
                buf.append(line.strip())
        if name is not None:
            seqs[name] = "".join(buf).replace(" ", "").replace("\t", "")
    return seqs


def translate(seq: str, table: Dict[str, str], stop_codons: List[str], start_codons: List[str]) -> Tuple[str | None, str | None]:
    seq = seq.upper().replace("U", "T")
    if len(seq) % 3 != 0:
        return None, "length_not_multiple_of_3"
    aa: List[str] = []
    for i in range(0, len(seq), 3):
        codon = seq[i:i+3]
        if codon in stop_codons:
            aa.append("*")
            continue
        if codon not in table:
            return None, f"invalid_codon_{codon}"
        if i == 0 and codon in start_codons:
            aa.append("M")  # translate start codon as Met
        else:
            aa.append(table[codon])
    return "".join(aa), None


def run(
    faa_path: str,
    cds_path: str,
    out_faa: str,
    out_cds: str,
    codon_table: int,
) -> Dict[str, int]:
    if codon_table not in CODON_TABLES:
        raise ValueError(f"未支持的 codon_table={codon_table}")
    table = CODON_TABLES[codon_table]
    stop_codons = CODON_STOP_CODONS[codon_table]
    start_codons = CODON_START_CODONS[codon_table]
    faa_seqs = parse_fasta(faa_path)
    cds_seqs = parse_fasta(cds_path)

    kept = []
    stats = {
        "length_not_multiple_of_3": 0,
        "invalid_codon": 0,
        "internal_stop": 0,
        "mismatch": 0,
        "missing_cds": 0,
        "paired_by_order": 0,
    }

    matching_names = sum(1 for name in faa_seqs if name in cds_seqs)
    if matching_names == 0:
        if len(faa_seqs) != len(cds_seqs):
            raise RuntimeError("名称不匹配且序列数量不同，无法按顺序配对")
        stats["paired_by_order"] = 1
        pairs = list(zip(faa_seqs.items(), cds_seqs.items()))
    else:
        pairs = []
        for name, prot in faa_seqs.items():
            cds = cds_seqs.get(name)
            if cds is None:
                stats["missing_cds"] += 1
                continue
            pairs.append(((name, prot), (name, cds)))

    for (name, prot), (_, cds) in pairs:
        aa, err = translate(cds, table, stop_codons, start_codons)
        if err:
            if err == "length_not_multiple_of_3":
                stats["length_not_multiple_of_3"] += 1
            elif err.startswith("invalid_codon_"):
                stats["invalid_codon"] += 1
            continue
        if "*" in aa[:-1]:
            stats["internal_stop"] += 1
            continue
        aa_trim = aa.rstrip("*")
        prot_trim = prot.rstrip("*").upper()
        if aa_trim != prot_trim:
            stats["mismatch"] += 1
            continue
        kept.append((name, prot, cds))

    if not kept:
        raise RuntimeError(f"所有序列均未通过质控 ({faa_path})")

    with open(out_faa, "w") as f_out, open(out_cds, "w") as c_out:
        for name, prot, cds in kept:
            f_out.write(f">{name}\n{prot}\n")
            c_out.write(f">{name}\n{cds}\n")

    return {"kept": len(kept), **stats}


def main() -> None:
    parser = argparse.ArgumentParser(description="过滤含终止/frameshift/不匹配的序列")
    parser.add_argument("--faa", required=True, help="输入蛋白 fasta (与 cds 对应)")
    parser.add_argument("--cds", required=True, help="输入 CDS fasta")
    parser.add_argument("--out-faa", required=True, help="输出过滤后蛋白 fasta")
    parser.add_argument("--out-cds", required=True, help="输出过滤后 CDS fasta")
    parser.add_argument(
        "--codon-table",
        type=int,
        default=11,
        help="密码子表 ID (NCBI translation table)",
    )
    args = parser.parse_args()

    try:
        stats = run(
            faa_path=args.faa,
            cds_path=args.cds,
            out_faa=args.out_faa,
            out_cds=args.out_cds,
            codon_table=args.codon_table,
        )
    except Exception as exc:  # noqa: BLE001
        sys.stderr.write(f"ERROR: {exc}\n")
        sys.exit(1)

    sys.stderr.write(
        "QC: {kept} kept; paired_by_order={paired_by_order}; "
        "missing_cds={missing_cds}, len%3={length_not_multiple_of_3}, "
        "invalid_codon={invalid_codon}, internal_stop={internal_stop}, "
        "mismatch={mismatch}\n".format(**stats)
    )


if __name__ == "__main__":
    main()
